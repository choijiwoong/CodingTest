class Solution {
    public int calc_gcd(int a, int b){
        while(b>0){
            int tmp = a;
            a=b;
            b=tmp%b;
        }
        return a;
    }


    public int solution(int[][] signals) {
        int answer = -1;
        int length = signals.length;
        int KIND_COLOR = 3;

        // 그래. 처음부터 뭔가 하기보다 예외처리부터 한 뒤 진행하자.
        // 1. 각 색 변환 주기 계산
        int[] sum = new int[length];
        for(int i=0; i<length; i++){
            sum[i]=0;
            for(int j=0; j<KIND_COLOR; j++)
                sum[i] += signals[i][j];
        }

        // 2. 입력 패턴의 최소공배수 계산
        int gcd = sum[0];
        for(int i=0; i<length-1; i++)
            gcd = calc_gcd(gcd, sum[i+1]);

        // 3. 만약 최소 공배수가 20 초과면 -1 반환
        if(gcd>20)
            return -1;

        // 4. 메인 로직
        for(int t=1; t<=6460; t++){
            // 현재 노란불인가요?
            int result = 1;
            for(int depth=0; depth<length; depth++){
                int[] tmp = signals[depth];
                int idx = t%sum[depth];
                if( !(signals[depth][0]<idx && idx<=signals[depth][0]+signals[depth][1]) ){
                    result=0;
                    break;
                }
            }

            // 아니면 리턴
            if(result == 1)
                return answer=t;
        }

        // 5. 디버깅1: 현재 max t를 구하지 못하고 있음. 최악의 상황으로 노란 주기가 20, 19, 17이라고 생각해보자. 이들의 최소공배수는? 6,460. 결과 정확도 60%임.
        // 6. 디버깅2: 방향성은 맞아보이는데.. 최악의 주기가 몇이 가능할까?
        // 노트북 킬 힘은 없고.. 머리로 검토라도 해보자. 명확한 t의 최대를 찾을 필요 없어보이는데. 대충 20*20*20이 가장 큰 값일테고 명확하진 않아도 그렇게 수행하면 더찾아보면 더 봤지 덜보진 않을듯. 그렇게 실행해보면 좋고, 어제 끄기전에 그걸 빼고도 또 문제가 있던거로 기억함. 검토나 해보자. 검토 시 결고ㅓ보이면 그건 내일 커밋하자. 고생했다.


        return answer;
    }
}

